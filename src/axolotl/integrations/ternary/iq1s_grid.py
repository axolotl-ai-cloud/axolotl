def grid_tensor(device: torch.device | str = "cpu") -> torch.Tensor:
    """The (2048, 8) int8 pattern table, cached per device."""
    key = str(device)
    if key not in _cache:
        raw = base64.b64decode(_GRID_B64)
        table = torch.frombuffer(bytearray(raw), dtype=torch.int8).reshape(
            GRID_ENTRIES, GRID_DIM
        )
        _cache[key] = table.to(device)
    return _cache[key]


def pattern_index_table(device: torch.device | str = "cpu") -> torch.Tensor:
    """Map any of the 3^8 ternary patterns (base-3 key over codes+1) to its grid
    index, or -1 — the scalar-pre-round pruning: ~70% of real weight groups hit."""
    key = "idx:" + str(device)
    if key not in _cache:
        table = torch.full((3**GRID_DIM,), -1, dtype=torch.long)
        grid = grid_tensor().long() + 1
        powers = torch.tensor([3**i for i in range(GRID_DIM)], dtype=torch.long)
        table[(grid * powers).sum(dim=1)] = torch.arange(GRID_ENTRIES)
        _cache[key] = table.to(device)
    return _cache[key]
